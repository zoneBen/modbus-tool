impl ScanLinkInput {
    pub fn link(&self) -> Result<LinkConfig, String> {
        build_link(
            self.transport,
            self.framing,
            self.host.clone(),
            self.port,
            self.serial_port.clone(),
            self.baud_rate,
            self.data_bits,
            self.parity.as_deref(),
            self.stop_bits,
            "",
        )
    }

    pub fn timeout(&self) -> std::time::Duration {
        std::time::Duration::from_millis(self.timeout_ms.unwrap_or(200).clamp(50, 5000))
    }
}

